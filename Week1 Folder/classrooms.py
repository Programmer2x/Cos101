# Purpose: This program calculates the total number of chairs in a classroom
# that has a fixed number of rows, with the same number of chairs in each row.

# Input
rows = 6
chairs_per_row = 8

# Process
total_chairs = rows * chairs_per_row

# Output
print("Number of rows:", rows)
print("Chairs per row:", chairs_per_row)
print("Total number of chairs:", total_chairs)
